"""Markdown reports with safe filenames and escaped HTML preview."""
from __future__ import annotations

import html
import re
import time
import uuid
from pathlib import Path

from .settings import settings

TEMPLATE = """# {title}

**Engagement:** {client} | **Date (UTC):** {date} | **Prepared with:** RatanSec Super Agent v2
{roe_line}

---

{body}

---

_Generated by RatanSec Super Agent · session `{session}`_

> Authorization references are operator-supplied records, not cryptographic proof of client consent.
> Review findings and evidence before sharing. Audit ledger: `data/superagent/audit.jsonl`.
"""


def _slug(text: str) -> str:
    return (re.sub(r"[^A-Za-z0-9]+", "-", text.strip().lower()).strip("-") or "report")[:60]


def save(title: str, markdown: str, *, session: str = "", client: str = "", roe: str = "") -> Path:
    stamp = time.strftime("%Y%m%d-%H%M%S", time.gmtime())
    name = f"{stamp}-{_slug(title)}-{uuid.uuid4().hex[:6]}.md"
    path = settings.reports_dir / name
    content = TEMPLATE.format(title=title.strip() or "Security Assessment Report", client=client or "(internal)",
                              date=time.strftime("%d %b %Y, %H:%M", time.gmtime()),
                              roe_line=(f"\n**Authorization record:** `{roe}`" if roe else ""),
                              body=markdown.strip(), session=session)
    path.write_text(content, encoding="utf-8")
    path.chmod(0o600)
    return path


def list_reports() -> list[dict]:
    items = []
    for path in sorted(settings.reports_dir.glob("*.md"), key=lambda p: p.stat().st_mtime, reverse=True):
        stat = path.stat()
        items.append({"name": path.name, "size": stat.st_size, "modified": stat.st_mtime,
                      "modified_str": time.strftime("%Y-%m-%d %H:%M", time.gmtime(stat.st_mtime))})
    return items


def _safe(name: str) -> Path:
    if "/" in name or "\\" in name or name.startswith(".") or not name.endswith(".md"):
        raise ValueError("invalid name")
    path = (settings.reports_dir / name).resolve()
    if path.parent != settings.reports_dir.resolve():
        raise ValueError("invalid path")
    return path


def read(name: str) -> str:
    path = _safe(name)
    if not path.is_file():
        raise FileNotFoundError(name)
    return path.read_text(encoding="utf-8")


def delete(name: str) -> bool:
    path = _safe(name)
    if not path.is_file():
        return False
    path.unlink()
    return True


def _inline(text: str) -> str:
    safe = html.escape(text, quote=True)
    safe = re.sub(r"`([^`]+)`", r"<code>\1</code>", safe)
    safe = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", safe)
    safe = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<em>\1</em>", safe)
    safe = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r'<a href="\2" target="_blank" rel="noopener noreferrer">\1</a>', safe)
    return safe


def md_to_html(markdown: str) -> str:
    out: list[str] = []
    in_code = in_list = in_table = False
    def close() -> None:
        nonlocal in_list, in_table
        if in_list: out.append("</ul>"); in_list = False
        if in_table: out.append("</tbody></table>"); in_table = False
    for raw in markdown.splitlines():
        line = raw.rstrip()
        if line.startswith("```"):
            close(); out.append("</code></pre>" if in_code else "<pre><code>"); in_code = not in_code; continue
        if in_code: out.append(html.escape(line)); continue
        if not line.strip(): close(); continue
        if line.startswith("|") and line.endswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c): continue
            if not in_table:
                close(); out.append("<table><thead><tr>" + "".join(f"<th>{_inline(c)}</th>" for c in cells) + "</tr></thead><tbody>"); in_table = True
            else: out.append("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in cells) + "</tr>")
            continue
        close()
        if m := re.match(r"^(#{1,6})\s+(.*)", line):
            level = len(m.group(1)); out.append(f"<h{level}>{_inline(m.group(2))}</h{level}>"); continue
        if line.startswith(("- ", "* ")):
            if not in_list: out.append("<ul>"); in_list = True
            out.append(f"<li>{_inline(line[2:])}</li>"); continue
        if line.startswith("> "): out.append(f"<blockquote>{_inline(line[2:])}</blockquote>"); continue
        if line.strip() == "---": out.append("<hr>"); continue
        out.append(f"<p>{_inline(line)}</p>")
    close()
    if in_code: out.append("</code></pre>")
    return "\n".join(out)
