"""Reports — Markdown files + HTML template (client-ready)."""

from __future__ import annotations

import re
import time
from pathlib import Path

from .settings import settings

TEMPLATE = """# {title}

**Engagement:** {client} &nbsp;|&nbsp; **Date:** {date} &nbsp;|&nbsp; **Prepared by:** RatanSec Super Agent
{roe_line}

---

{body}

---

_Generated by RatanSec Super Agent · session `{session}`_

> **Authorization:** Yeh assessment sirf client ki likhit permission ke saath kiya gaya.
> Har command ka record audit chain me hai (`data/superagent/audit.jsonl`).
"""


def _slug(text: str) -> str:
    clean = re.sub(r"[^A-Za-z0-9]+", "-", text.strip().lower()).strip("-")
    return (clean or "report")[:60]


def save(title: str, markdown: str, *, session: str = "", client: str = "", roe: str = "") -> Path:
    stamp = time.strftime("%Y%m%d-%H%M%S")
    name = f"{stamp}-{_slug(title)}.md"
    path = settings.reports_dir / name
    content = TEMPLATE.format(
        title=title.strip() or "Security Assessment Report",
        client=client or "(internal)",
        date=time.strftime("%d %b %Y, %H:%M"),
        roe_line=(f"\n**Authorization record:** `{roe}`" if roe else ""),
        body=markdown.strip(),
        session=session,
    )
    path.write_text(content, encoding="utf-8")
    return path


def list_reports() -> list[dict]:
    items = []
    for path in sorted(settings.reports_dir.glob("*.md"), key=lambda p: p.stat().st_mtime, reverse=True):
        stat = path.stat()
        items.append({
            "name": path.name,
            "size": stat.st_size,
            "modified": stat.st_mtime,
            "modified_str": time.strftime("%Y-%m-%d %H:%M", time.localtime(stat.st_mtime)),
        })
    return items


def read(name: str) -> str:
    path = _safe(name)
    if not path.is_file():
        raise FileNotFoundError(name)
    return path.read_text(encoding="utf-8")


def delete(name: str) -> bool:
    try:
        path = _safe(name)
    except ValueError:
        return False
    if not path.is_file():
        return False
    path.unlink()
    return True


def _safe(name: str) -> Path:
    if "/" in name or "\\" in name or name.startswith("."):
        raise ValueError("invalid name")
    path = (settings.reports_dir / name).resolve()
    if not str(path).startswith(str(settings.reports_dir.resolve())):
        raise ValueError("invalid path")
    return path


def md_to_html(markdown: str) -> str:
    """Chhota markdown -> HTML (browser ke print/PDF ke liye, koi dependency nahi)."""
    lines = markdown.splitlines()
    out: list[str] = []
    in_code = False
    in_list = False
    table_open = False

    def close_list() -> None:
        nonlocal in_list
        if in_list:
            out.append("</ul>")
            in_list = False

    def close_table() -> None:
        nonlocal table_open
        if table_open:
            out.append("</table>")
            table_open = False

    for raw in lines:
        line = raw.rstrip()
        if line.startswith("```"):
            close_list()
            close_table()
            out.append("<pre><code>" if not in_code else "</code></pre>")
            in_code = not in_code
            continue
        if in_code:
            out.append(_esc(line))
            continue
        if not line.strip():
            close_list()
            close_table()
            continue
        if line.startswith("|") and line.endswith("|"):
            close_list()
            cells = [c.strip() for c in line.strip("|").split("|")]
            if all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c):
                continue
            if not table_open:
                out.append("<table><thead>")
                out.append("<tr>" + "".join(f"<th>{_inline(c)}</th>" for c in cells) + "</tr></thead><tbody>")
                table_open = True
            else:
                out.append("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in cells) + "</tr>")
            continue
        close_table()
        if re.match(r"^#{1,6}\s", line):
            close_list()
            level = len(line) - len(line.lstrip("#"))
            out.append(f"<h{level}>{_inline(line[level:].strip())}</h{level}>")
            continue
        if line.startswith(("- ", "* ")):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{_inline(line[2:])}</li>")
            continue
        if line.startswith("> "):
            close_list()
            out.append(f"<blockquote>{_inline(line[2:])}</blockquote>")
            continue
        if line.strip() == "---":
            close_list()
            out.append("<hr />")
            continue
        close_list()
        out.append(f"<p>{_inline(line)}</p>")
    close_list()
    close_table()
    if in_code:
        out.append("</code></pre>")
    return "\n".join(out)


def _esc(text: str) -> str:
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def _inline(text: str) -> str:
    safe = _esc(text).replace("&amp;nbsp;", "&nbsp;").replace("&amp;mdash;", "&mdash;")
    safe = re.sub(r"`([^`]+)`", r"<code>\1</code>", safe)
    safe = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", safe)
    safe = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<em>\1</em>", safe)
    safe = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r'<a href="\2" target="_blank" rel="noopener">\1</a>', safe)
    return safe
