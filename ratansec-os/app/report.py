"""Report builder — run ka Markdown report + AI summary."""

from __future__ import annotations

import re
import time
from pathlib import Path

from .config import settings
from .executor import Run

_SAFE_NAME = re.compile(r"[^A-Za-z0-9._-]+")


def _timestamp(ts: float | None) -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(ts)) if ts else "-"


def run_summary_table(run: Run) -> list[dict]:
    rows = []
    for s in run.steps:
        rows.append(
            {
                "tool": s.tool,
                "label": s.label,
                "status": s.status,
                "exit_code": s.exit_code,
                "duration": s.duration,
                "error": s.error,
            }
        )
    return rows


def build_markdown(run: Run, ai_summary: str | None = None) -> str:
    lines: list[str] = [
        f"# RatanSec OS — Scan Report",
        "",
        f"| Field | Value |",
        f"|---|---|",
        f"| Run ID | `{run.id}` |",
        f"| Target | `{run.target}` |",
        f"| Profile | `{run.profile}` |",
        f"| Source | `{run.source}` |",
        f"| Actor | `{run.actor}` |",
        f"| Started | {_timestamp(run.created)} |",
        f"| Finished | {_timestamp(run.finished)} |",
        f"| Status | `{run.status}` |",
        "",
    ]
    if run.note:
        lines += [f"> {run.note}", ""]

    # Steps table
    lines += ["## Steps", "", "| # | Tool | Command | Status | Exit | Time |", "|---|---|---|---|---|---|"]
    for s in run.steps:
        cmd = s.command.replace("|", "\\|")
        lines.append(f"| {s.index + 1} | {s.tool} | `{cmd}` | {s.status} | {s.exit_code} | {s.duration}s |")
    lines.append("")

    if ai_summary:
        lines += ["## AI Analysis", "", ai_summary.strip(), ""]

    # Raw outputs
    lines += ["## Raw Output", ""]
    for s in run.steps:
        lines += [f"### {s.index + 1}. {s.label}", "", f"```", s.command, f"```", ""]
        if s.output:
            lines += ["```", s.output.strip()[:20000], "```", ""]
        if s.error:
            lines += [f"**Note:** {s.error}", ""]

    lines += [
        "---",
        "",
        "_Generated by RatanSec OS. Yeh report sirf authorized security testing ke liye hai._",
        "",
    ]
    return "\n".join(lines)


def safe_name(name: str, run: Run) -> str:
    base = _SAFE_NAME.sub("-", (name or "").strip()) or f"report-{run.target.replace('.', '-')}-{run.id}"
    if not base.endswith(".md"):
        base += ".md"
    return base[:120]


def save(run: Run, name: str | None = None, ai_summary: str | None = None) -> Path:
    settings.ensure_dirs()
    path = settings.reports_dir / safe_name(name or "", run)
    path.write_text(build_markdown(run, ai_summary), encoding="utf-8")
    return path


def list_reports() -> list[dict]:
    settings.ensure_dirs()
    items = []
    for path in sorted(settings.reports_dir.glob("*.md"), key=lambda p: p.stat().st_mtime, reverse=True):
        stat = path.stat()
        items.append({"name": path.name, "size": stat.st_size, "modified": stat.st_mtime})
    return items


def read_report(name: str) -> str:
    path = settings.reports_dir / Path(name).name
    if not path.is_file():
        raise FileNotFoundError("report nahi mila")
    return path.read_text(encoding="utf-8")


def delete_report(name: str) -> bool:
    path = settings.reports_dir / Path(name).name
    if path.is_file():
        path.unlink()
        return True
    return False
